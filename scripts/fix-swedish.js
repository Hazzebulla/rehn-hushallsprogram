const fs = require("fs");
const files = process.argv.slice(2);
const cp = (...codes) => String.fromCharCode(...codes);
const replacements = [
  [cp(0xc3, 0xa5), cp(0xe5)],
  [cp(0xc3, 0xa4), cp(0xe4)],
  [cp(0xc3, 0xb6), cp(0xf6)],
  [cp(0xc3, 0x85), cp(0xc5)],
  [cp(0xc3, 0x84), cp(0xc4)],
  [cp(0xc3, 0x96), cp(0xd6)],
  [cp(0xc2, 0xb0), cp(0xb0)],
  [cp(0xc2, 0xb2), cp(0xb2)],
  [cp(0xc2, 0xbd), cp(0xbd)],
  [cp(0xe2, 0x80, 0xa2), cp(0x2022)],
  [cp(0xe2, 0x86, 0x92), cp(0x2192)],
  [cp(0xe2, 0x80, 0x93), cp(0x2013)],
  [cp(0xe2, 0x80, 0x9d), cp(0x201d)],
  [cp(0xe2, 0x80, 0x9c), cp(0x201c)],
  [cp(0xe2, 0x80, 0x99), cp(0x2019)],
  [cp(0xc2, 0x20), " "],
];
for (const file of files) {
  let text = fs.readFileSync(file, "utf8");
  for (const [from, to] of replacements) text = text.split(from).join(to);
  fs.writeFileSync(file, text, "utf8");
}
